import type { HHMM, LatLng, Place, TimeRange, WeekHours } from './types'

const r = (open: HHMM, close: HHMM): TimeRange => ({ open, close })

/** Same hours every day. */
function daily(open: HHMM, close: HHMM): WeekHours {
  const t = r(open, close)
  return { mon: t, tue: t, wed: t, thu: t, fri: t, sat: t, sun: t }
}

/** Closed on Mondays, otherwise the same hours; `overrides` replaces single days. */
function closedMon(open: HHMM, close: HHMM, overrides: Partial<WeekHours> = {}): WeekHours {
  return { ...daily(open, close), mon: null, ...overrides }
}

